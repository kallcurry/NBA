let nameRegex = null;
let replacementMap = null;

function ensureRegex() {
  if (nameRegex) return;
  const entries = Object.entries(DISPLAY_NAMES)
    .filter(([en]) => en.length > 2)
    .sort((a, b) => b[0].length - a[0].length);
  replacementMap = new Map(entries.map(([en, zh]) => [en.toLowerCase(), zh]));
  const pattern = entries
    .map(([en]) => en.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'))
    .join('|');
  nameRegex = new RegExp(`(?<![A-Za-z])(${pattern})(?![A-Za-z])`, 'gi');
}

/** Replace known English player names inside play-by-play text. */
export function localizePlayerNames(text) {
  if (!text) return '';
  ensureRegex();
  return String(text).replace(nameRegex, (match) => replacementMap.get(match.toLowerCase()) || match);
}
